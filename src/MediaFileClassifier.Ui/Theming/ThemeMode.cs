namespace MediaFileClassifier.Ui.Theming;

/// <summary>
/// Which theme the app shows.
/// </summary>
public enum ThemeMode
{
    /// <summary>
    /// Follow the system's light or dark setting. The default.
    /// </summary>
    System,

    /// <summary>
    /// Always light.
    /// </summary>
    Light,

    /// <summary>
    /// Always dark.
    /// </summary>
    Dark,
}
